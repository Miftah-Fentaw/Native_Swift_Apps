// Writes the generated sections of the root README from the website's data,
// so the README and the website always agree. Each section sits between
//   <!-- name:start --> and <!-- name:end -->
// markers; everything outside the markers is hand-written and left alone.
//
//   npm run readme              rewrite every generated section
//   npm run readme -- --check   exit with an error if the README is out of date
//
// Runs on Node 22.18+ (TypeScript type stripping).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SITE_URL, allScreens, community, licenseLabel, projects, roadmap, type Level, type Project } from '../src/data/projects.ts'
import { patterns } from '../src/data/patterns.ts'
import { glossary, topics, tracks } from '../src/data/learn.ts'
import { sitePages } from '../src/data/pages.ts'

const README = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'README.md')
const NOTE = (name: string) =>
  `<!-- Generated by website/scripts/readme.ts (${name}). Edit the website data, then run \`npm run readme\` in website/. -->`

const LEVEL_COLOR: Record<Level, string> = { Beginner: '34C759', Intermediate: 'FF9F0A', Advanced: 'FF453A' }
const LEVEL_DOT: Record<Level, string> = { Beginner: '🟢', Intermediate: '🟠', Advanced: '🔴' }

/** shields.io static badge text: `-` and `_` are escaped by doubling; keep `·` readable like the rest of the README. */
const badgeText = (s: string) => encodeURIComponent(s.replace(/-/g, '--').replace(/_/g, '__')).replace(/%C2%B7/g, '·')
const badge = (text: string, color: string, apple = false) =>
  `https://img.shields.io/badge/${badgeText(text)}-${color}?style=flat-square${apple ? '&logo=apple&logoColor=white' : ''}`

const site = (path: string) => `${SITE_URL}#${path}`

/** Puts Swift attributes and modifiers in code spans, so `@Observable` isn't rendered as a GitHub @mention. */
const codeify = (s: string) => s.replace(/(^|[\s(])([@.][A-Za-z]\w*)/g, '$1`$2`')

// ---------------------------------------------------------------------------
// Explore More: the community app tables
// ---------------------------------------------------------------------------

function row(p: Project) {
  const repo = p.repo!
  const owner = repo.split('/')[0]
  const url = `https://github.com/${repo}`
  const platforms = p.platforms ?? ''
  return `  <tr>
    <td width="56" align="center"><a href="${url}"><img src="https://github.com/${owner}.png?size=88" width="44" height="44" alt="${owner} on GitHub"></a></td>
    <td>
      <a href="${url}"><b>${p.name}</b></a>&nbsp;
      <img src="${badge(p.level, LEVEL_COLOR[p.level])}" alt="${p.level}" height="16">
      <img src="${badge(platforms, '1C1C1E', true)}" alt="${platforms.replace(/ · /g, ', ')}" height="16">
      <img src="${badge(licenseLabel(p), '8E8E93')}" alt="${licenseLabel(p)}" height="16">
      <img src="https://img.shields.io/github/stars/${repo}?style=flat-square&label=%E2%98%85&color=1C1C1E" alt="GitHub stars" height="16"><br>
      <sub>${p.tagline}</sub>
    </td>
    <td width="80" align="right"><a href="${url}"><sub>GitHub&nbsp;→</sub></a></td>
  </tr>`
}

// Names that stay capitalized at the start of a list item.
const PROPER_WORDS = new Set(['Swift', 'App', 'Apple', 'Siri', 'Shortcuts', 'Combine', 'Observation', 'Rust', 'Mac', 'Bluetooth'])
const PROPER_PHRASES = ['Live Activities', 'Watch Connectivity', 'Face ID', 'Touch ID', 'Dynamic Type']

/** Lower-cases an item's first word unless it's a name, so the items read as one sentence. */
const lowerFirst = (item: string) => {
  const first = item.split(/[\s/,]/)[0]
  const isName = PROPER_WORDS.has(first) || PROPER_PHRASES.some((p) => item.startsWith(p)) || /^.+[A-Z]/.test(first)
  if (isName || !/^[A-Z]/.test(first)) return item
  return item[0].toLowerCase() + item.slice(1)
}

const sentence = (items: string[]) => {
  const text = items.map((item, i) => codeify(i === 0 ? item : lowerFirst(item))).join(', ')
  return text.endsWith('.') ? text : `${text}.`
}

function exploreMore() {
  const parts: string[] = []
  for (const level of ['Beginner', 'Intermediate', 'Advanced'] as Level[]) {
    const apps = community.filter((p) => p.level === level)
    parts.push(
      '',
      `### ${level}`,
      '',
      '<table>',
      ...apps.map(row),
      '</table>',
      '',
      apps.map((p) => `**${p.name}:** ${sentence(p.learn)}${p.note ? ` *${p.note}*` : ''}`).join('  \n'),
    )
  }
  return parts.join('\n')
}

// ---------------------------------------------------------------------------
// Hub stats: a row of large badges under the title
// ---------------------------------------------------------------------------

function hubStats() {
  const stat = (value: number, label: string, color: string, path: string) =>
    `<a href="${site(path)}"><img src="https://img.shields.io/badge/${value}-${encodeURIComponent(label)}-${color}?style=for-the-badge&labelColor=1C1C1E" alt="${value} ${label}"></a>`
  return [
    '',
    '<p align="center">',
    stat(projects.length, 'apps in this repo', '5B4FE0', '/explore?source=repo'),
    stat(community.length, 'community apps', '2F80ED', '/explore?source=community'),
    stat(patterns.length, 'code patterns', 'E0794F', '/patterns'),
    stat(tracks.length, 'learning tracks', '30A46C', '/learn'),
    stat(allScreens.length, 'screenshots', 'BF5AF2', '/gallery'),
    stat(glossary.length, 'glossary terms', '8E8E93', '/glossary'),
    '</p>',
    '',
  ].join('\n')
}

// ---------------------------------------------------------------------------
// Learning tracks
// ---------------------------------------------------------------------------

function learningTracks() {
  const name = (slug: string) => [...projects, ...community].find((p) => p.slug === slug)?.name ?? slug
  const lines = [
    '',
    '| Track | Level | The path |',
    '| :--- | :--- | :--- |',
    ...tracks.map((t) => {
      const path = [...new Set(t.steps.map((s) => s.app))].map((slug) => {
        const repo = projects.some((p) => p.slug === slug)
        return repo ? `**${name(slug)}**` : name(slug)
      })
      return `| [${t.title}](${site(`/learn?t=${t.id}`)}) | ${LEVEL_DOT[t.level]} ${t.level} | ${path.join(' → ')} |`
    }),
    '',
    `<sub>**Bold** apps are in this repository; the rest are [community apps](#explore-more). Each step on the [Learn page](${site('/learn')}) says what to look at.</sub>`,
    '',
  ]
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Feature matrix: what each app in this repo uses
// ---------------------------------------------------------------------------

function featureMatrix() {
  const tech = topics.filter((t) => !t.isPlatform && t.apps.some((p) => projects.includes(p)))
  const header = `| | ${projects.map((p) => `[**${p.name}**](${p.folder}/)`).join(' | ')} |`
  const align = `| :--- | ${projects.map(() => ':---:').join(' | ')} |`
  const rows = tech.map(
    (t) => `| [${t.name}](${site(`/topics/${t.slug}`)}) | ${projects.map((p) => (p.tech.includes(t.name) ? '✅' : '·')).join(' | ')} |`,
  )
  const level = `| *Level* | ${projects.map((p) => `${LEVEL_DOT[p.level]} ${p.level}`).join(' | ')} |`
  const screens = `| *Screenshots* | ${projects.map((p) => String(p.screens.length)).join(' | ')} |`
  const code = `| *Code patterns* | ${projects.map((p) => `[${patterns.filter((x) => x.project === p.slug).length}](${site(`/patterns?app=${p.slug}`)})`).join(' | ')} |`
  return ['', header, align, level, ...rows, screens, code, ''].join('\n')
}

// ---------------------------------------------------------------------------
// Code patterns
// ---------------------------------------------------------------------------

function codePatterns() {
  const lines = ['', '| Pattern | App | Frameworks |', '| :--- | :--- | :--- |']
  for (const p of projects) {
    for (const x of patterns.filter((x) => x.project === p.slug)) {
      lines.push(`| [${codeify(x.title)}](${site(`/patterns?p=${x.id}`)}) | ${p.name} | ${x.tech.join(', ')} |`)
    }
  }
  lines.push('')
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Website pages
// ---------------------------------------------------------------------------

function sitePagesTable() {
  return [
    '',
    '| Page | What’s there |',
    '| :--- | :--- |',
    `| [Home](${SITE_URL}) | Animated tour of the apps, a tabbed library, community apps by level, *Ask the hub* search and the learning path |`,
    ...sitePages.map((p) => `| [${p.title}](${site(p.path)}) | ${p.description} |`),
    `| Project pages | One per app: screenshots, features, what you’ll learn, run steps, code patterns and tracks |`,
    '',
  ].join('\n')
}

// ---------------------------------------------------------------------------

const sections: Record<string, () => string> = {
  'hub-stats': hubStats,
  'learning-tracks': learningTracks,
  'feature-matrix': featureMatrix,
  'code-patterns': codePatterns,
  'site-pages': sitePagesTable,
  'explore-more': exploreMore,
}

const readme = readFileSync(README, 'utf8')
let next = readme
for (const [name, build] of Object.entries(sections)) {
  const start = `<!-- ${name}:start -->`
  const end = `<!-- ${name}:end -->`
  const a = next.indexOf(start)
  const b = next.indexOf(end)
  if (a === -1 || b === -1) {
    console.error(`README.md needs the ${start} and ${end} markers.`)
    process.exit(1)
  }
  next = `${next.slice(0, a)}${start}\n${NOTE(name)}\n${build()}\n${end}${next.slice(b + end.length)}`
}

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md is out of date. Run `npm run readme` in website/.')
    process.exit(1)
  }
  console.log('README.md generated sections are up to date.')
} else {
  writeFileSync(README, next)
  console.log(`Wrote ${Object.keys(sections).length} generated sections (${community.length} community apps, ${roadmap.length} planned) to README.md.`)
}
